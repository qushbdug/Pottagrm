def get_system_stats():
    """Get current system statistics"""
    try:
        # Get bot process info
        result = subprocess.run(['ps', 'aux'], capture_output=True, text=True)
        lines = result.stdout.split('\n')
        bot_process = None
        for line in lines:
            if 'python3 main.py' in line and 'grep' not in line:
                parts = line.split()
                if len(parts) >= 11:
                    bot_process = {
                        'pid': parts[1],
                        'cpu': parts[2],
                        'memory': parts[3],
                        'memory_kb': parts[5],
                        'time': parts[9]
                    }
                break
        
        # Get database size
        db_size = 0
        if os.path.exists('/workspace/yemen_net.db'):
            db_size = os.path.getsize('/workspace/yemen_net.db') / (1024*1024)
        
        return bot_process, db_size
    except:
        return None, 0

